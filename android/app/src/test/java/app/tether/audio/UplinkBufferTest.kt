package app.tether.audio

import app.tether.helper.UplinkBuffer
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import kotlin.math.sin

/**
 * The helper's uplink against simulated traces: the iPhone's 20 ms frames delivered by Bluetooth connection events
 * every 15 ms, hold-ups of 60-77 ms every few seconds, clock drift, a slow start, and the inject track (40 ms buffer)
 * draining at the call's clock. Compared with the policy it replaced (8-frame queue, oldest dropped when full, one
 * frame trimmed after ≥ 2 stayed queued for a second).
 */
class UplinkBufferTest {
    private val rate = 16000
    private val frame = 320

    interface Policy { fun push(pcm: ShortArray, ns: Long, track: Int); fun poll(): ShortArray?; fun queued(): Int; fun underruns(n: Int) {} }

    class NewPolicy : Policy {
        val b = UplinkBuffer()
        override fun push(pcm: ShortArray, ns: Long, track: Int) = b.push(pcm, ns, track)
        override fun poll() = b.poll()
        override fun queued() = b.size
        override fun underruns(n: Int) = b.noteUnderruns(n)
    }

    /** The policy before: ArrayBlockingQueue(8), drop-oldest, trim one frame after 50 writes with ≥ 2 queued. */
    class OldPolicy : Policy {
        val q = ArrayDeque<ShortArray>(); var dropped = 0; var trimmed = 0; private var highSince = 0
        override fun push(pcm: ShortArray, ns: Long, track: Int) { while (q.size >= 8) { q.removeFirst(); dropped++ }; q.addLast(pcm) }
        override fun poll(): ShortArray? {
            val s = q.removeFirstOrNull() ?: return null
            if (q.size >= 2) { if (++highSince >= 50) { q.removeFirst(); trimmed++; highSince = 0 } } else highSince = 0
            return s
        }
        override fun queued() = q.sumOf { it.size }
    }

    data class Result(val voiceLostMs: Double, val quietCutMs: Double, val compressedMs: Double, val insertedMs: Double, val stretchedMs: Double,
                      val underrunMs: Double, val avgDelayMs: Double, val endDelayMs: Double, val overflow: Int)

    /**
     * [drift]: the iPhone's microphone clock against the track's (+0.02 = 2 % more frames than the track plays);
     * [holdEveryMs] / [holdMs]: a Bluetooth hold-up (no connection event delivers) of that length every so often;
     * [startBurst]: frames already queued when the track starts (sent before the helper was ready).
     */
    private fun run(p: Policy, seconds: Int = 20, drift: Double = 0.0, holdEveryMs: Int = 0, holdMs: IntArray = intArrayOf(70),
                    startBurst: Int = 0, eventMs: Int = 15, sinkPeriodMs: Int = 1): Result {
        val totalMs = seconds * 1000
        // Speech: 1.5 s talk spurts (loud) and 0.6 s pauses (room noise at about -60 dBFS).
        fun voiced(i: Long) = (i % (rate * 21 / 10)) < rate * 15 / 10
        fun sample(i: Long): Short = if (voiced(i)) (6000 * sin(i * 0.07) + 3000 * sin(i * 0.31)).toInt().toShort()
            else ((i * 7919 % 61) - 30).toShort()
        var produced = 0L          // samples generated by the "microphone"
        val pendingFrames = ArrayDeque<Pair<ShortArray, Boolean>>()   // waiting for a connection event
        var voiceFramesIn = 0
        repeat(startBurst) { val f = ShortArray(frame) { k -> sample(produced + k) }; produced += frame; p.push(f, 0, 0); voiceFramesIn++ }
        val period = 20.0 / (1 + drift)
        var nextFrameAt = 0.0
        var holdLeft = 0; var holdIdx = 0
        // Track: 40 ms buffer, drained 16 samples per ms; the writer blocks while it is full (WRITE_BLOCKING).
        val cap = 640; var trackQueued = 0; var started = false; var underrun = 0; var underrunEvents = 0
        var cur: ShortArray? = null; var pos = 0
        var delaySum = 0.0; var delayN = 0; var endDelay = 0.0
        for (ms in 0 until totalMs) {
            val ns = ms * 1_000_000L
            while (nextFrameAt <= ms) {
                val f = ShortArray(frame) { k -> sample(produced + k) }; produced += frame
                pendingFrames.addLast(f to voiced(produced - frame / 2)); nextFrameAt += period
            }
            if (holdEveryMs > 0 && ms > 0 && ms % holdEveryMs == 0) { holdLeft = holdMs[holdIdx++ % holdMs.size] }
            if (holdLeft > 0) holdLeft-- else if (ms % eventMs == 0) {
                // A connection event carries up to 3 frames (more after a hold-up: every event drains what is waiting).
                var n = 0
                while (pendingFrames.isNotEmpty() && (n < 3 || pendingFrames.size > 3)) { p.push(pendingFrames.removeFirst().first, ns, trackQueued + (cur?.let { it.size - pos } ?: 0)); voiceFramesIn++; n++ }
            }
            // The track's mixer takes a period's worth at a time (16 samples per ms); short of that it is an underrun.
            if (started && ms % sinkPeriodMs == 0) {
                val want = 16 * sinkPeriodMs; val take = minOf(want, trackQueued)
                if (take < want) { underrun += want - take; underrunEvents++ }
                trackQueued -= take
                if (ms > 1000) p.underruns(underrunEvents)   // as the helper: not while the path starts up
            }
            // The writer fills the track as far as it has room.
            while (true) {
                if (cur == null) { cur = p.poll() ?: break; pos = 0; if (cur.isEmpty()) { cur = null; continue } }
                val n = minOf(cur.size - pos, cap - trackQueued)
                trackQueued += n; pos += n; if (trackQueued > 0) started = true
                if (pos >= cur.size) cur = null else break
            }
            val d = (p.queued() + trackQueued + (cur?.let { it.size - pos } ?: 0)) * 1000.0 / rate
            if (ms > 2000) { delaySum += d; delayN++ }
            endDelay = d
        }
        val ms = { s: Int -> s * 1000.0 / rate }
        return when (p) {
            is NewPolicy -> Result(p.b.overflowFrames * 20.0, ms(p.b.quietCut), ms(p.b.compressed), ms(p.b.inserted), ms(p.b.stretched), ms(underrun),
                delaySum / delayN, endDelay, p.b.overflowFrames)
            is OldPolicy -> Result((p.dropped + p.trimmed) * 20.0, 0.0, 0.0, 0.0, 0.0, ms(underrun), delaySum / delayN, endDelay, p.dropped)
            else -> error("policy")
        }
    }

    private fun compare(name: String, f: (Policy) -> Result): Pair<Result, Result> {
        val old = f(OldPolicy()); val new = f(NewPolicy())
        println("%-34s before: lost %5.0f ms, underrun %5.0f ms, delay %3.0f ms | after: lost %4.0f ms, quiet cut %4.0f / in %4.0f, speech -%3.0f / +%3.0f, underrun %4.0f ms, delay %3.0f ms (end %3.0f)"
            .format(name, old.voiceLostMs, old.underrunMs, old.avgDelayMs, new.voiceLostMs, new.quietCutMs, new.insertedMs, new.compressedMs, new.stretchedMs, new.underrunMs, new.avgDelayMs, new.endDelayMs))
        return old to new
    }

    // Hold-ups as measured on the reference link (2026-11-23: worst gaps 60-76 ms, a few per call): no connection event
    // for 45-62 ms, plus the 15 ms event spacing.
    private val holds = intArrayOf(45, 62, 51, 57)

    @Test fun steadyLinkKeepsDelayLowAndLosesNothing() {
        val (_, n) = compare("steady (15 ms events)") { run(it) }
        assertEquals(0.0, n.voiceLostMs, 0.0)
        assertTrue("compressed ${n.compressedMs}", n.compressedMs < 10)
        assertTrue("delay ${n.avgDelayMs}", n.avgDelayMs < 35)
    }

    @Test fun holdUpsAreAbsorbedWithoutLosingVoice() {
        val (o, n) = compare("hold-ups (gaps 60-77 ms) every 3 s") { run(it, holdEveryMs = 3000, holdMs = holds) }
        assertEquals(0, n.overflow)
        assertEquals(0.0, n.voiceLostMs, 0.0)
        // After the first hold-up a cushion covers most of the next ones: far fewer gaps, about the same delay.
        assertTrue("underrun ${n.underrunMs} vs ${o.underrunMs}", n.underrunMs < o.underrunMs * 0.8)
        assertTrue("delay ${n.avgDelayMs} vs ${o.avgDelayMs}", n.avgDelayMs < o.avgDelayMs + 5)
    }

    @Test fun fastMicrophoneClockIsTakenOutInPauses() {
        val (o, n) = compare("iPhone clock +2 %, hold-ups") { run(it, drift = 0.02, holdEveryMs = 3000, holdMs = holds) }
        assertEquals(0.0, n.voiceLostMs, 0.0)
        assertTrue(o.voiceLostMs > 0)
        // 2 % of 20 s is ~400 ms: mostly cut in pauses, the rest by speeding speech up.
        assertTrue("quiet cut ${n.quietCutMs}", n.quietCutMs > 100)
        assertTrue("delay ${n.avgDelayMs} vs ${o.avgDelayMs}", n.avgDelayMs < o.avgDelayMs - 20)
    }

    @Test fun slowMicrophoneClockIsFilledInPauses() {
        val (o, n) = compare("iPhone clock -2 %") { run(it, drift = -0.02) }
        assertTrue("underrun ${n.underrunMs} vs ${o.underrunMs}", n.underrunMs < o.underrunMs / 4)
        assertEquals(0.0, n.voiceLostMs, 0.0)
        assertTrue("delay ${n.avgDelayMs}", n.avgDelayMs < 40)
    }

    @Test fun unreadTestLineSinkKeepsTheDelayBounded() {
        // The test line without a far-end reader drained the track at 14.4 kHz: 10 % more frames than it played.
        val (o, n) = compare("sink 10 % slow (unread test line)") { run(it, drift = 0.10) }
        assertTrue(o.voiceLostMs > 1000)
        assertEquals(0, n.overflow)
        assertTrue("delay ${n.avgDelayMs}", n.avgDelayMs < 200)
    }

    @Test fun aMixerTakingWholePeriodsGetsItsCushion() {
        // The test line's remote submix takes 32 ms at a time, a real call's mixer 20 ms: the target learns it.
        for (period in intArrayOf(20, 32)) {
            val (o, n) = compare("mixer period $period ms") { run(it, sinkPeriodMs = period) }
            assertEquals(0.0, n.voiceLostMs, 0.0)
            assertTrue("underrun ${n.underrunMs} vs ${o.underrunMs}", n.underrunMs <= maxOf(80.0, o.underrunMs))
            assertTrue("delay ${n.avgDelayMs}", n.avgDelayMs < 70)
        }
    }

    @Test fun framesSentBeforeTheTrackStartedAreKept() {
        // 15 frames (300 ms) waiting when the helper starts: kept, then drained in the pauses.
        val (o, n) = compare("start burst of 15 frames") { run(it, startBurst = 15) }
        assertTrue(o.voiceLostMs >= 140)
        assertEquals(0.0, n.voiceLostMs, 0.0)
        assertTrue("end delay ${n.endDelayMs}", n.endDelayMs < 40)
    }

    @Test fun targetFollowsTheLongestRecentGap() {
        val b = UplinkBuffer()
        var t = 0L
        fun after(gapMs: Long, then: Int = 30) { t += gapMs * 1_000_000L; b.push(ShortArray(frame), t); repeat(then) { t += 20_000_000L; b.push(ShortArray(frame), t) } }
        after(0, 100)
        assertEquals(5 * rate / 1000, b.target)                           // even 20 ms frames: 5 ms
        after(60)                                                          // a 60 ms hold-up: 42 ms ahead
        assertEquals(42 * rate / 1000, b.target)
        after(120)                                                         // a long hold-up: capped at 45 ms
        assertEquals(45 * rate / 1000, b.target)
        after(20, 500)                                                     // 10 s without: back to 5 ms
        assertEquals(5 * rate / 1000, b.target)
        after(800)                                                         // a stall no cushion covers: not counted
        assertEquals(5 * rate / 1000, b.target)
        repeat(8) { after(120, 40) }                                       // hold-ups every second (tethering): up to 60 ms
        assertEquals(60 * rate / 1000, b.target)
    }

    @Test fun aLongStallIsCaughtUpAtOnceQuietFramesFirst() {
        val b = UplinkBuffer()
        var t = 0L
        val loud = ShortArray(frame) { (8000 * sin(it * 0.2)).toInt().toShort() }
        repeat(100) { t += 20_000_000L; b.push(loud.copyOf(), t, 320); b.poll() }   // steady, 20 ms in the track
        // An 800 ms stall (Bluetooth tethering, 2026-11-24), then its 40 frames at once, every other one a pause.
        t += 800_000_000L
        repeat(40) { i -> b.push(if (i % 2 == 0) ShortArray(frame) { ((i * 31 + it) % 7 - 3).toShort() } else loud.copyOf(), t, 320) }
        val keep = b.target + rate * UplinkBuffer.KEEP_MS / 1000
        assertTrue("queue ${b.size} + track 320 vs ${keep + frame}", b.size + 320 <= keep + frame)
        assertTrue("late cut ${b.lateCut}", b.lateCut >= 30 * frame)
        // The pauses went first: what is left is the latest speech.
        val left = generateSequence { b.poll() }.toList()
        assertTrue(left.drop(1).all { UplinkBuffer.meanSquare(it) > UplinkBuffer.QUIET_MS })
        assertEquals("faded in from the last sample written", loud[frame - 1].toDouble(), left.first()[0].toDouble(), 600.0)
    }

    @Test fun aStallDoesNotLeaveTheDelayBehind() {
        // Stalls of 800 ms every 5 s: without the late cut 800 ms stayed ahead until enough pauses came (537 ms ahead,
        // 1.6 s cut in pauses on the reference phone, 2026-11-24).
        val (_, n) = compare("stalls of 800 ms every 5 s") { run(it, holdEveryMs = 5000, holdMs = intArrayOf(800)) }
        assertEquals(0, n.overflow)
        assertTrue("delay ${n.avgDelayMs}", n.avgDelayMs < 80)
        assertTrue("end delay ${n.endDelayMs}", n.endDelayMs < 120)
    }

    @Test fun tetheringHoldUpsGetACushion() {
        // Hold-ups of 60-80 ms every second (Bluetooth tethering on): the target covers them, so few run the track dry.
        val (o, n) = compare("hold-ups 60-80 ms every 1 s") { run(it, holdEveryMs = 1000, holdMs = intArrayOf(50, 65, 58, 62)) }
        assertEquals(0.0, n.voiceLostMs, 0.0)
        assertTrue("underrun ${n.underrunMs} vs ${o.underrunMs}", n.underrunMs < o.underrunMs * 0.9)
        assertTrue("delay ${n.avgDelayMs}", n.avgDelayMs < 90)
    }

    @Test fun overflowDropsTheOldestOnlyBeyondOneSecond() {
        // Before the track plays (-1) nothing is late yet: only a full second overflows.
        val b = UplinkBuffer()
        repeat(50) { b.push(ShortArray(frame) { _ -> (10000 + it).toShort() }, it * 1_000_000L, -1) }
        assertEquals(0, b.overflowFrames)
        b.push(ShortArray(frame) { 99 }, 51_000_000L, -1)
        assertEquals(1, b.overflowFrames)
        assertEquals(10001, b.poll()!![0].toInt())   // frame 0 went (loud frames: sped up, never cut)
    }

    @Test fun resampleKeepsEndsAndLength() {
        val f = ShortArray(320) { (it * 10).toShort() }
        val r = UplinkBuffer.resample(f, 310)
        assertEquals(310, r.size)
        assertEquals(0, r[0].toInt())
        assertEquals(3190, r[309].toInt())
    }
}
